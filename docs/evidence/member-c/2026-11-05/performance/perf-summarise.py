#!/usr/bin/env python3
"""Turn the D10 perf probe's raw output into one table.

The probe writes "KEY=value" lines and leaves every sample in place; this script
only collects them. It deliberately does not average the show() stage or print a
single "startup time": the spread between runs is the finding, and a summary
number would invite quoting it as a device result.

Usage: perf-summarise.py <rundir>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

KEY_VALUE = re.compile(r"^([A-Za-z0-9_]+)=(.*)$")


def read_pairs(path: Path) -> tuple[dict[str, list[str]], list[str]]:
    """Return all KEY=value pairs (in order, duplicates kept) and comment lines."""

    pairs: dict[str, list[str]] = {}
    comments: list[str] = []
    if not path.is_file():
        return pairs, comments

    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.rstrip()
        if not line:
            continue
        if line.startswith("#"):
            comments.append(line)
            continue
        match = KEY_VALUE.match(line)
        if not match:
            continue
        key, value = match.group(1), match.group(2)
        pairs.setdefault(key, []).append(value)
    return pairs, comments


def one(pairs: dict[str, list[str]], key: str, default: str = "-") -> str:
    values = pairs.get(key)
    return values[-1] if values else default


def last_number(value: str) -> float | None:
    """Pull the ms figure out of one sample line.

    Two shapes reach here and both must keep working: the scaling rows are
    "rows,step,ms" (the number is last) and the keystroke rows carry the step as
    a separate field, "ms step=b". Reading only the last comma-separated field
    silently reduced the keystroke column to "-", which is exactly the kind of
    quiet hole this file exists to avoid.
    """

    head = value.split()[0] if value.split() else ""
    for candidate in (head, value.split(",")[-1]):
        try:
            return float(candidate)
        except ValueError:
            continue
    return None


def stats(values: list[str]) -> str:
    numbers = [n for n in (last_number(v) for v in values) if n is not None]
    if not numbers:
        return "-"
    numbers.sort()
    return "%.3f / %.3f / %.3f" % (numbers[0], numbers[len(numbers) // 2], numbers[-1])


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2

    outdir = Path(argv[1])
    runs = [p for p in outdir.glob("run-*") if p.is_dir()]
    runs.sort(key=lambda p: int(p.name.split("-")[1]) if p.name.split("-")[1].isdigit() else 0)

    if not runs:
        print("no run-* directories under %s" % outdir, file=sys.stderr)
        return 1

    lines: list[str] = []
    lines.append("# D10 performance baseline — collected runs")
    lines.append("")
    lines.append("Generated by perf-summarise.py from the probe output in this directory.")
    lines.append("")
    lines.append("Host only: WSL2 x86-64, Qt 6.12, QT_QPA_PLATFORM=offscreen. See")
    lines.append("docs/release/已知问题.md, section 性能边界, for what these numbers may")
    lines.append("and may not be used for.")
    lines.append("")

    lines.append("startup_with_show_ms in show.txt is the WHOLE probe run, not first launch:"
                 " it performs show() five times. First launch is startup_before_show_ms plus"
                 " the first show_stage_ms sample. Quoting startup_with_show_ms as first"
                 " launch overstates it by roughly a hundred milliseconds.")
    lines.append("")
    lines.append("| run | library cold (ms) | library warm (ms) | CreateWidgets (ms) | "
                 "SetDefaultPart (ms) | keystroke min/median/max (ms) | show stage (ms) | pieces |")
    lines.append("|---" * 8 + "|")

    for run in runs:
        core, _ = read_pairs(run / "core.txt")
        show, _ = read_pairs(run / "show.txt")
        lines.append(
            "| %s | %s | %s | %s | %s | %s | %s | %s |"
            % (
                run.name,
                one(core, "library_cold_ms"),
                stats(core.get("library_warm_ms", [])),
                one(core, "createwidgets_ms"),
                one(core, "setdefaultpart_ms"),
                stats(core.get("keystroke_ms", [])),
                stats(show.get("show_stage_ms", [])),
                one(core, "library_cold_pieces", one(show, "library_pieces")),
            )
        )

    lines.append("")
    lines.append("## Filter cost by library size (synthetic)")
    lines.append("")
    lines.append("SetFilter() time in ms for one filter step, over a list widened to N rows.")
    lines.append("")
    lines.append("| rows | step | ms |")
    lines.append("|---|---|---|")
    for run in runs[:1]:
        core, _ = read_pairs(run / "core.txt")
        for value in core.get("scaling_row", []):
            parts = value.split(",")
            if len(parts) == 3:
                lines.append("| %s | %s | %s |" % (parts[0], parts[1], parts[2]))

    lines.append("")
    lines.append("## Environment of the collecting run")
    lines.append("")
    for run in runs[:1]:
        _, comments = read_pairs(run / "core.txt")
        for comment in comments:
            lines.append("- " + comment.lstrip("# ").strip())

    (outdir / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s" % (outdir / "summary.md"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
