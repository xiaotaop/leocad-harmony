#!/usr/bin/env bash
# D10 performance baseline: build and run the probe.
#
# The probe has to be compiled against the real qmake project, and leocad.pro
# resolves its source list relative to its own directory, so a probe .pro that
# includes it only works from the repository root. This script therefore stages
# the files there, builds in a scratch directory outside the tree, runs both
# modes, and removes the staged files again on exit (trap, so an interrupted run
# does not leave them behind).
#
# Usage:
#   scripts/dev/perf-baseline.sh [outdir]
#
# Environment:
#   Requires .devtools/env.sh to have been sourced (qmake on PATH).
#   JOBS          parallel make jobs (default 4; this host has 7 GB of RAM)
#   PERF_ROUNDS   completed runs to collect (default 3)
#
# Output, under <outdir>:
#   run-<n>/core.txt, run-<n>/show.txt, plus .err files and build logs
#   summary.md, generated by perf-summarise.py
#
# Cold means cold: every run gets a fresh, empty XDG_CACHE_HOME, so "cold" is
# "no description index on disk", which is what a first launch on a device has.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PERF_DIR="$REPO_ROOT/docs/evidence/member-c/2026-11-05/performance"
OUTDIR="${1:-$PERF_DIR/runs}"
JOBS="${JOBS:-4}"
ROUNDS="${PERF_ROUNDS:-3}"
ARCHIVE="$REPO_ROOT/assets/ldraw-lite/library-lite.zip"
BUILD="/tmp/bd-perf"
QT_LIB="$REPO_ROOT/.devtools/Qt/6.12.0/gcc_64/lib"

if ! command -v qmake >/dev/null 2>&1; then
    echo "error: qmake not on PATH; source .devtools/env.sh first" >&2
    exit 2
fi

if [ ! -f "$ARCHIVE" ]; then
    echo "error: parts archive not found: $ARCHIVE" >&2
    exit 2
fi

STAGED_PRO="$REPO_ROOT/perf-baseline.pro"
STAGED_CPP="$REPO_ROOT/perf-baseline.cpp"

cleanup() {
    rm -f "$STAGED_PRO" "$STAGED_CPP"
}
trap cleanup EXIT INT TERM

cp "$PERF_DIR/perf-baseline.pro" "$STAGED_PRO"
cp "$PERF_DIR/perf-baseline.cpp" "$STAGED_CPP"

mkdir -p "$OUTDIR"

# Reuse an existing shadow build when the qmake project has not changed: a full
# rebuild costs minutes and the numbers do not depend on the build directory.
if ! ( cd "$BUILD" && qmake "$STAGED_PRO" CONFIG+=debug CONFIG-=debug_and_release ) > "$OUTDIR/qmake.log" 2>&1; then
    echo "error: qmake failed; see $OUTDIR/qmake.log" >&2
    tail -20 "$OUTDIR/qmake.log" >&2
    exit 1
fi

echo "== build =="
if ! make -C "$BUILD" -j"$JOBS" > "$OUTDIR/build.log" 2>&1; then
    echo "error: make failed; see $OUTDIR/build.log" >&2
    tail -40 "$OUTDIR/build.log" >&2
    exit 1
fi

BINARY="$BUILD/build/debug/leocad-perf"
if [ ! -x "$BINARY" ]; then
    echo "error: build produced no binary at $BINARY" >&2
    exit 1
fi

echo "== run =="
for Run in $(seq 1 "$ROUNDS"); do
    RunDir="$OUTDIR/run-$Run"
    CacheDir="$BUILD/cache-run-$Run"
    rm -rf "$RunDir" "$CacheDir"
    mkdir -p "$CacheDir" "$RunDir"

    echo "  run $Run: core"
    XDG_CACHE_HOME="$CacheDir" \
    LD_LIBRARY_PATH="$QT_LIB:${LD_LIBRARY_PATH:-}" \
    QT_QPA_PLATFORM=offscreen \
    LEOCAD_PERF_ARCHIVE="$ARCHIVE" \
    "$BINARY" core > "$RunDir/core.txt" 2> "$RunDir/core.err"

    echo "  run $Run: show"
    rm -rf "$CacheDir"
    mkdir -p "$CacheDir"
    XDG_CACHE_HOME="$CacheDir" \
    LD_LIBRARY_PATH="$QT_LIB:${LD_LIBRARY_PATH:-}" \
    QT_QPA_PLATFORM=offscreen \
    LEOCAD_PERF_ARCHIVE="$ARCHIVE" \
    "$BINARY" show > "$RunDir/show.txt" 2> "$RunDir/show.err"
done

echo "== summarise =="
python3 "$PERF_DIR/perf-summarise.py" "$OUTDIR"

echo "done: $OUTDIR"
