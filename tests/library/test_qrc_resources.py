#!/usr/bin/env python3
"""Tests for the Qt resource manifest and the bundled library wiring.

Two failure modes these cover:
  * a resource listed in a .qrc that does not exist, which breaks `rcc` at build
    time (the `.qm` files are generated by `lrelease` first, so they are expected
    to be absent in a fresh checkout and are handled separately);
  * the curated parts library not being reachable through the qrc alias that
    lcPiecesLibrary::FindBundledLibraryArchive() looks for.
"""

from __future__ import annotations

import importlib.util
import sys
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

LEOCAD_QRC = REPO_ROOT / "leocad.qrc"
STYLESHEET_QRC = REPO_ROOT / "resources" / "stylesheet" / "stylesheet.qrc"
LIBRARY_ARCHIVE = REPO_ROOT / "assets" / "ldraw-lite" / "library-lite.zip"
MAINWINDOW_LIBRARY = REPO_ROOT / "common" / "lc_library.cpp"


def load_checker():
    path = REPO_ROOT / "scripts" / "library" / "check_qrc_resources.py"
    spec = importlib.util.spec_from_file_location("check_qrc_resources", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules["check_qrc_resources"] = module
    spec.loader.exec_module(module)
    return module


def qrc_entries(path: Path) -> list[tuple[str, str]]:
    """Return [(prefix, file-or-alias)] for a .qrc."""
    root = ET.parse(path).getroot()
    entries: list[tuple[str, str]] = []
    for resource in root.iter("qresource"):
        prefix = resource.get("prefix", "")
        for element in resource.iter("file"):
            text = (element.text or "").strip()
            if text:
                entries.append((prefix, text, element.get("alias", "")))
    return entries


class QrcResourceTests(unittest.TestCase):
    def test_qrc_files_parse(self):
        for path in (LEOCAD_QRC, STYLESHEET_QRC):
            with self.subTest(qrc=path.name):
                ET.parse(path)

    def test_all_non_generated_resources_exist(self):
        checker = load_checker()
        for relative in ("leocad.qrc", "resources/stylesheet/stylesheet.qrc"):
            with self.subTest(qrc=relative):
                result = checker.check(relative)
                self.assertEqual(result["missing"], [],
                                 f"{relative}: missing {result['missing']}")

    def test_only_qm_files_are_build_generated(self):
        """Anything generated at build time must be a compiled translation."""
        checker = load_checker()
        result = checker.check("leocad.qrc")
        for name in result["generated"]:
            self.assertTrue(name.endswith(".qm"),
                            f"{name} is missing but not a generated .qm")

    def test_curated_library_is_registered_with_its_expected_alias(self):
        entries = qrc_entries(LEOCAD_QRC)
        aliases = {alias: text for _prefix, text, alias in entries if alias}
        expected = "assets/ldraw-lite/library-lite.zip"
        self.assertIn(expected, aliases,
                      "curated library not registered with the alias "
                      "FindBundledLibraryArchive() looks for")
        self.assertEqual(aliases[expected],
                         "assets/ldraw-lite/library-lite.zip")

    def test_curated_library_asset_exists(self):
        self.assertTrue(LIBRARY_ARCHIVE.exists(),
                        "assets/ldraw-lite/library-lite.zip missing; run "
                        "scripts/library/build_library.py")

    def test_builtin_fallback_library_is_still_packaged(self):
        """The 128-part built-in archive stays as a last resort."""
        entries = qrc_entries(LEOCAD_QRC)
        texts = {text for _prefix, text, _alias in entries}
        self.assertIn("resources/library.zip", texts,
                      "resources/library.zip must stay packaged: "
                      "LoadBuiltinPieces() depends on it")

    def test_translation_catalogues_are_registered(self):
        entries = qrc_entries(LEOCAD_QRC)
        texts = {text for _prefix, text, _alias in entries}
        self.assertIn("resources/leocad_zh_CN.qm", texts)


class LibraryDiscoveryTests(unittest.TestCase):
    """The bundled-library probe must match the loader's contract."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.library = MAINWINDOW_LIBRARY.read_text("utf-8")

    def test_probe_returns_a_path_the_loader_accepts(self):
        """FindBundledLibraryArchive must be declared and defined."""
        header = (REPO_ROOT / "common" / "lc_library.h").read_text("utf-8")
        self.assertIn("static QString FindBundledLibraryArchive();", header)
        self.assertIn("QString lcPiecesLibrary::FindBundledLibraryArchive()",
                      self.library)

    def test_probe_checks_data_dir_binary_dir_and_qrc(self):
        """All three deployment layouts must be covered, in that order."""
        body = self.library
        self.assertIn("AppLocalDataLocation", body,
                      "application data directory not probed")
        self.assertIn("applicationDirPath", body,
                      "binary directory not probed")
        self.assertIn(":/assets/ldraw-lite/library-lite.zip", body,
                      "compiled-in fallback not probed")

        data_index = body.index("AppLocalDataLocation")
        binary_index = body.index("applicationDirPath")
        qrc_index = body.index(":/assets/ldraw-lite/library-lite.zip")
        self.assertLess(data_index, binary_index,
                        "data directory must be preferred over the binary dir")
        self.assertLess(binary_index, qrc_index,
                        "the compiled-in copy must be the last resort")

    def test_probe_does_not_change_loader_behaviour(self):
        """Load() must keep its existing contract; the probe only supplies a path."""
        self.assertIn("bool lcPiecesLibrary::Load(const QString& LibraryPath, "
                      "bool ShowProgress)", self.library)

    def test_color_configuration_loads_from_the_supplied_archive(self):
        """The curated archive must carry ldconfig.ldr, or colours silently reset."""
        self.assertIn('ExtractFile("ldraw/ldconfig.ldr"', self.library)


if __name__ == "__main__":
    unittest.main()
